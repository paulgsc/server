#!/usr/bin/env python3
"""Each binary's NixOS options, generated from its schema (#408).

`infra/env/<binary>.json` is each binary's clap `Config` (CFG7, #503); this
writes `nix/modules/generated/<binary>.nix` from it, so the NixOS module that
runs the binary declares no variable of its own. Each variable becomes one
option, `services.<binary>.settings.<NAME>`, typed after its kind and null by
default (null: the binary's own default). A secret becomes no option at all:
the store is world-readable, so a secret reaches the container only through
`environmentFiles` (sops-nix, on the host). Each generated file also lists
what the module asserts: the variables that are required, those required
while another is on, and the limits a number is held to while its feature is
on, so `nixos-rebuild` names every gap in one evaluation, as `make preflight`
does for compose.

  python3 scripts/nixos_options.py            write nix/modules/generated/*.nix
  python3 scripts/nixos_options.py --check    fail when one differs (CI)

Stdlib only, like scripts/env_schema.py, whose schema reader it shares.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from env_schema import REPO_ROOT, load_schemas  # noqa: E402

OUT = REPO_ROOT / "nix" / "modules" / "generated"

TYPES = {
    "bool": "lib.types.bool",
    "u16": "lib.types.port",
    "u32": "lib.types.ints.u32",
    "u64": "lib.types.ints.unsigned",
    "usize": "lib.types.ints.unsigned",
    "seconds": "lib.types.ints.unsigned",
    "number": "(lib.types.either lib.types.float lib.types.int)",
    "socket_addr": "lib.types.str",
    "path": "lib.types.str",
    "string": "lib.types.str",
}


def string(text: str) -> str:
    """`text` as a Nix string literal."""
    return json.dumps(text, ensure_ascii=False).replace("${", "\\${")


def option_type(variable: dict) -> str:
    if variable["kind"] == "enum":
        inner = "(lib.types.enum [ " + " ".join(string(value) for value in variable["values"]) + " ])"
    else:
        inner = TYPES[variable["kind"]]
    if variable["delimiter"]:
        inner = f"(lib.types.listOf {inner})"
    return f"lib.types.nullOr {inner}"


def description(variable: dict) -> str:
    text = variable["help"].strip()
    if variable["default"] is not None:
        text += f"\n\nUnset (null), the binary's default: `{variable['default']}`."
    else:
        text += "\n\nUnset (null), the binary's own behaviour for an unset variable."
    if variable["required"]:
        text += " Required."
    condition = variable.get("required_when")
    if condition:
        text += f" Required while {condition['variable']} is {condition['value']}."
    return text


def render(schema: dict) -> str:
    variables = schema["variables"]
    settings = [variable for variable in variables if not variable["secret"]]
    lines = [
        f"# GENERATED by scripts/nixos_options.py from infra/env/{schema['binary']}.json: do not edit.",
        "# `make env-schema` regenerates it; CI fails when it differs.",
        "{lib}: {",
        "  # One option per variable the binary reads, but its secrets.",
        "  settings = {",
    ]
    for variable in settings:
        lines += [
            f"    {variable['name']} = lib.mkOption {{",
            f"      type = {option_type(variable)};",
            "      default = null;",
            f"      description = {string(description(variable))};",
            "    };",
        ]
    lines += ["  };", ""]

    def names(chosen: list[dict]) -> str:
        return "[" + "".join(f" {string(variable['name'])}" for variable in chosen) + " ]"

    lines.append("  # The variables the binary refuses to start without.")
    lines.append(f"  required = {names([variable for variable in variables if variable['required']])};")
    lines.append("  # Its secrets: no option, only `environmentFiles`.")
    lines.append(f"  secrets = {names([variable for variable in variables if variable['secret']])};")
    lines.append("  # The binary's defaults, for the conditions below.")
    lines.append("  defaults = {")
    for variable in variables:
        if variable["default"] is not None and not variable["secret"]:
            lines.append(f"    {variable['name']} = {string(variable['default'])};")
    lines.append("  };")
    lines.append("  # Required while another variable has a value (the binary's RULES).")
    lines.append("  requiredWhen = [")
    for variable in variables:
        condition = variable.get("required_when")
        if condition:
            lines.append(
                f"    {{ variable = {string(variable['name'])}; when = {string(condition['variable'])}; is = {string(condition['value'])}; }}"
            )
    lines.append("  ];")
    lines.append("  # A number's limits while each of `when` holds; \"*\" is any value but an empty one.")
    lines.append("  bounds = [")
    for variable in variables:
        bounds = variable.get("bounds")
        if bounds:
            when = " ".join(f"{{ variable = {string(item['variable'])}; is = {string(item['value'])}; }}" for item in bounds["when"])
            low = "null" if bounds.get("min") is None else json.dumps(bounds["min"])
            high = "null" if bounds.get("max") is None else json.dumps(bounds["max"])
            when = f"[ {when} ]" if when else "[]"
            lines.append(f"    {{ variable = {string(variable['name'])}; min = {low}; max = {high}; when = {when}; }}")
    lines.append("  ];")
    lines.append("}")
    return "\n".join(lines) + "\n"


def file_name(binary: str) -> str:
    return binary.replace("-", "_") + ".nix"


def self_test() -> None:
    schema = {
        "binary": "probe-x",
        "about": "",
        "variables": [
            {"name": "ON", "group": None, "required": False, "default": "false", "kind": "bool", "values": [], "delimiter": None, "secret": False, "help": "On.", "required_when": None},
            {"name": "URL", "group": None, "required": False, "default": None, "kind": "string", "values": [], "delimiter": None, "secret": False, "help": "Say ${x}.", "required_when": {"variable": "ON", "value": "true"}},
            {"name": "KEY", "group": None, "required": True, "default": None, "kind": "string", "values": [], "delimiter": None, "secret": True, "help": "Key.", "required_when": None},
            {"name": "MODE", "group": None, "required": False, "default": "a", "kind": "enum", "values": ["a", "b"], "delimiter": None, "secret": False, "help": "Mode.", "required_when": None},
            {"name": "LIST", "group": None, "required": False, "default": None, "kind": "string", "values": [], "delimiter": ",", "secret": False, "help": "List.", "required_when": None},
            {
                "name": "SECONDS", "group": None, "required": False, "default": "60", "kind": "u64", "values": [], "delimiter": None, "secret": False, "help": "Seconds.",
                "required_when": None, "bounds": {"min": 60.0, "max": None, "when": [{"variable": "ON", "value": "true"}]},
            },
        ],
    }
    text = render(schema)
    assert "KEY = lib.mkOption" not in text and 'secrets = [ "KEY" ];' in text, "a secret is no option"
    assert 'required = [ "KEY" ];' in text
    assert 'type = lib.types.nullOr (lib.types.enum [ "a" "b" ]);' in text
    assert "type = lib.types.nullOr (lib.types.listOf lib.types.str);" in text
    assert '"Say \\${x}.' in text, "a ${ in help text is not interpolated"
    assert '{ variable = "URL"; when = "ON"; is = "true"; }' in text
    assert '{ variable = "SECONDS"; min = 60.0; max = null; when = [ { variable = "ON"; is = "true"; } ]; }' in text, text
    assert file_name("some-obs") == "some_obs.nix"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs")
    parser.add_argument("--self-test", action="store_true", help="test the renderer first")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        print("nixos_options self-test: ok")
    stale = []
    for schema in load_schemas():
        path = OUT / file_name(schema["binary"])
        rendered = render(schema)
        if args.check:
            if not path.exists() or path.read_text() != rendered:
                stale.append(str(path.relative_to(REPO_ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered)
    if stale:
        print("not what infra/env/*.json generate: " + ", ".join(stale) + ". Run `make env-schema` and commit what it writes.")
        return 1
    if args.check:
        print("nix/modules/generated matches infra/env.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
