//! `nix/modules/generated/<binary>.nix`: each binary's NixOS options,
//! generated from its schema (#408).
//!
//! Each variable becomes one option, `services.<binary>.settings.<NAME>`,
//! typed after its kind and null by default (null: the binary's own default).
//! A secret becomes no option at all: the store is world-readable, so a
//! secret reaches the container only through `environmentFiles` (sops-nix, on
//! the host). Each file also lists what the module asserts, so
//! `nixos-rebuild` names every gap in one evaluation, as `make preflight`
//! does for compose.

use crate::schema::{Kind, Schema, Variable};
use std::fmt::Write as _;

/// `text` as a Nix string literal: JSON's escaping, and `${` kept literal.
pub(crate) fn string(text: &str) -> String {
	let mut out = String::from("\"");
	for character in text.chars() {
		match character {
			'"' => out.push_str("\\\""),
			'\\' => out.push_str("\\\\"),
			'\n' => out.push_str("\\n"),
			'\r' => out.push_str("\\r"),
			'\t' => out.push_str("\\t"),
			'\u{8}' => out.push_str("\\b"),
			'\u{c}' => out.push_str("\\f"),
			control if u32::from(control) < 0x20 => {
				let _ = write!(out, "\\u{:04x}", u32::from(control));
			}
			other => out.push(other),
		}
	}
	out.push('"');
	out.replace("${", "\\${")
}

/// A float as Python's `json.dumps` writes it: `60.0`, not `60`.
fn float(value: Option<f64>) -> String {
	value.map_or_else(
		|| "null".to_owned(),
		|value| {
			let text = value.to_string();
			if text.contains(['.', 'e', 'E']) || !value.is_finite() {
				text
			} else {
				format!("{text}.0")
			}
		},
	)
}

fn option_type(variable: &Variable) -> String {
	let inner = match variable.kind {
		Kind::Enum => format!("(lib.types.enum [ {} ])", variable.values.iter().map(|value| string(value)).collect::<Vec<_>>().join(" ")),
		Kind::Bool => "lib.types.bool".to_owned(),
		Kind::U16 => "lib.types.port".to_owned(),
		Kind::U32 => "lib.types.ints.u32".to_owned(),
		Kind::U64 | Kind::Usize | Kind::Seconds => "lib.types.ints.unsigned".to_owned(),
		Kind::Number => "(lib.types.either lib.types.float lib.types.int)".to_owned(),
		Kind::SocketAddr | Kind::Path | Kind::String => "lib.types.str".to_owned(),
	};
	let inner = if variable.delimiter.is_some() { format!("(lib.types.listOf {inner})") } else { inner };
	format!("lib.types.nullOr {inner}")
}

fn description(variable: &Variable) -> String {
	let mut text = variable.help.trim().to_owned();
	match &variable.default {
		Some(default) => {
			let _ = write!(text, "\n\nUnset (null), the binary's default: `{default}`.");
		}
		None => text.push_str("\n\nUnset (null), the binary's own behaviour for an unset variable."),
	}
	if variable.required {
		text.push_str(" Required.");
	}
	if let Some(condition) = &variable.required_when {
		let _ = write!(text, " Required while {} is {}.", condition.variable, condition.value);
	}
	text
}

fn names<'a>(chosen: impl Iterator<Item = &'a Variable>) -> String {
	let mut out = String::from("[");
	for variable in chosen {
		out.push(' ');
		out.push_str(&string(&variable.name));
	}
	out.push_str(" ]");
	out
}

pub(crate) fn render(schema: &Schema) -> String {
	let variables = &schema.variables;
	let mut lines = vec![
		format!("# GENERATED by envctl (`envctl nix`) from infra/env/{}.json: do not edit.", schema.binary),
		"# `make env-schema` regenerates it; CI fails when it differs.".to_owned(),
		"{lib}: {".to_owned(),
		"  # One option per variable the binary reads, but its secrets.".to_owned(),
		"  settings = {".to_owned(),
	];
	for variable in variables.iter().filter(|variable| !variable.secret) {
		lines.extend([
			format!("    {} = lib.mkOption {{", variable.name),
			format!("      type = {};", option_type(variable)),
			"      default = null;".to_owned(),
			format!("      description = {};", string(&description(variable))),
			"    };".to_owned(),
		]);
	}
	lines.extend(["  };".to_owned(), String::new()]);
	lines.push("  # The variables the binary refuses to start without.".to_owned());
	lines.push(format!("  required = {};", names(variables.iter().filter(|variable| variable.required))));
	lines.push("  # Its secrets: no option, only `environmentFiles`.".to_owned());
	lines.push(format!("  secrets = {};", names(variables.iter().filter(|variable| variable.secret))));
	lines.push("  # The binary's defaults, for the conditions below.".to_owned());
	lines.push("  defaults = {".to_owned());
	for variable in variables.iter().filter(|variable| !variable.secret) {
		if let Some(default) = &variable.default {
			lines.push(format!("    {} = {};", variable.name, string(default)));
		}
	}
	lines.push("  };".to_owned());
	lines.push("  # Required while another variable has a value (the binary's RULES).".to_owned());
	lines.push("  requiredWhen = [".to_owned());
	for variable in variables {
		if let Some(condition) = &variable.required_when {
			lines.push(format!(
				"    {{ variable = {}; when = {}; is = {}; }}",
				string(&variable.name),
				string(&condition.variable),
				string(&condition.value)
			));
		}
	}
	lines.push("  ];".to_owned());
	lines.push("  # A number's limits while each of `when` holds; \"*\" is any value but an empty one.".to_owned());
	lines.push("  bounds = [".to_owned());
	for variable in variables {
		if let Some(bounds) = &variable.bounds {
			let when: Vec<String> = bounds
				.when
				.iter()
				.map(|item| format!("{{ variable = {}; is = {}; }}", string(&item.variable), string(&item.value)))
				.collect();
			let when = if when.is_empty() { "[]".to_owned() } else { format!("[ {} ]", when.join(" ")) };
			lines.push(format!(
				"    {{ variable = {}; min = {}; max = {}; when = {when}; }}",
				string(&variable.name),
				float(bounds.min),
				float(bounds.max)
			));
		}
	}
	lines.push("  ];".to_owned());
	lines.push("}".to_owned());
	let mut text = lines.join("\n");
	text.push('\n');
	text
}

pub(crate) fn file_name(binary: &str) -> String {
	format!("{}.nix", binary.replace('-', "_"))
}

#[cfg(test)]
mod tests {
	use super::{file_name, render};
	use crate::schema::{
		fixture::{bounds, schema, var, when},
		Kind,
	};

	#[test]
	fn each_variable_is_an_option_but_a_secret() {
		let mut on = var("ON", Kind::Bool);
		on.default = Some("false".into());
		let mut url = var("URL", Kind::String);
		url.help = "Say ${x}.".into();
		url.required_when = Some(when("ON", "true"));
		let mut key = var("KEY", Kind::String);
		key.required = true;
		key.secret = true;
		let mut mode = var("MODE", Kind::Enum);
		mode.default = Some("a".into());
		mode.values = vec!["a".into(), "b".into()];
		let mut list = var("LIST", Kind::String);
		list.delimiter = Some(',');
		let mut seconds = var("SECONDS", Kind::U64);
		seconds.default = Some("60".into());
		seconds.bounds = Some(bounds(Some(60.0), None, &[("ON", "true")]));
		let mut ratio = var("RATIO", Kind::Number);
		ratio.bounds = Some(bounds(Some(0.0), Some(1e-7), &[]));
		let text = render(&schema("probe-x", vec![on, url, key, mode, list, seconds, ratio]));
		assert!(!text.contains("KEY = lib.mkOption") && text.contains("secrets = [ \"KEY\" ];") && text.contains("required = [ \"KEY\" ];"));
		assert!(text.contains("type = lib.types.nullOr (lib.types.enum [ \"a\" \"b\" ]);"));
		assert!(text.contains("type = lib.types.nullOr (lib.types.listOf lib.types.str);"));
		assert!(text.contains("\"Say \\${x}."), "a ${{ in help text is not interpolated");
		assert!(text.contains("{ variable = \"URL\"; when = \"ON\"; is = \"true\"; }"));
		assert!(
			text.contains("{ variable = \"SECONDS\"; min = 60.0; max = null; when = [ { variable = \"ON\"; is = \"true\"; } ]; }"),
			"{text}"
		);
		assert!(text.contains("min = 0.0; max = 0.0000001;") || text.contains("max = 1e-7;"), "{text}");
		assert_eq!(file_name("some-obs"), "some_obs.nix");
	}
}
